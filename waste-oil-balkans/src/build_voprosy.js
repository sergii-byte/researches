const fs = require('fs');
const { Document, Packer, Paragraph, TextRun, AlignmentType, BorderStyle } = require('docx');
const H = require('./helpers');
const { title, subtitle, H2, spacer } = H;

// One question: number + RU (bold), 中文 (gray) under it, then an answer line.
function item(n, ru, zh) {
  return [
    new Paragraph({
      spacing: { before: 140, after: 20, line: 264 },
      children: [
        new TextRun({ text: n + '. ', bold: true, size: 22, color: '1F3864' }),
        ...H.runs(ru),
      ],
    }),
    new Paragraph({
      spacing: { after: 40, line: 248 },
      children: [new TextRun({ text: zh, size: 19, color: '8A5A00' })],
    }),
    new Paragraph({
      spacing: { after: 60, line: 240 },
      border: { bottom: { style: BorderStyle.DOTTED, size: 4, color: 'BBBBBB', space: 2 } },
      children: [new TextRun({ text: 'Ответ / 答复:', size: 18, color: '999999' })],
    }),
  ];
}

const doc = new Document({
  creator: 'Проектная группа',
  title: 'Вопросы китайскому партнёру',
  styles: H.docDefaults,
  sections: [{
    properties: H.pageProps,
    children: [
      title('ВОПРОСЫ ПАРТНЁРУ / 致合作伙伴的问题'),
      subtitle('Партнёр даёт технологию и всё оборудование для завода регенерации в базовое масло Group II. Лицензии/роялти нет. Нужны ответы, чтобы посчитать экономику. · 合作伙伴提供技术与全部设备（无单独许可/提成）。请回答以便测算经济性。'),

      H2('Деньги и оборудование / 资金与设备'),
      ...item('1', 'Сколько стоит вся установка «под ключ» — отдельно на 10, 20 и 30 тыс. т/год? Если это ваш вклад в проект, а не продажа — в какую сумму вы её оцениваете и что хотите взамен (доля в бизнесе / возврат деньгами / забирать масло себе)?',
        '整套装置“交钥匙”价格分别为1万、2万、3万吨/年是多少？若为您对项目的出资而非出售——您如何估值、想要什么回报（股份/回款/包销基础油）？'),
      ...item('2', 'Что входит в эту цену и что НЕ входит (резервуары, монтаж, доработка под нормы Европы)?',
        '该价格含什么、不含什么（储罐、安装、按欧盟标准改造）？'),
      ...item('3', 'Сроки: изготовление + доставка + монтаж + пуск — сколько месяцев всего?',
        '周期：制造+运输+安装+开车——共几个月？'),
      ...item('4', 'Оплата: какой аванс и как разбито по этапам?',
        '付款：预付多少、如何分阶段？'),

      H2('Производство / 生产'),
      ...item('5', 'Из 1 тонны сырья — сколько на выходе базового масла? Сколько газойля и сколько остатка (гудрона)?',
        '每吨原料产出多少基础油？多少瓦斯油、多少残渣（渣油）？'),
      ...item('6', 'Расход на тонну переработки: электричество, газ/топливо, химия/адсорбент — три цифры (лучше фактические с вашего завода в Цзинане).',
        '每吨加工消耗：电、燃气/燃料、化学品/吸附剂——三个数字（最好是济南工厂实测值）。'),
      ...item('7', 'Сколько людей нужно на завод (по сменам и всего)?',
        '工厂需要多少人（按班次及总数）？'),

      H2('Качество — главный риск / 质量（主要风险）'),
      ...item('8', 'Это точно Group II? Пришлите паспорт продукта с вашего завода и образец — проверим в независимой лаборатории. Гарантируете ли Group II на НАШЕМ сырье (оно грязнее китайского)?',
        '确实是II类吗？请提供贵厂产品质量单和样品——我方送独立实验室检测。能否保证在我方原料（比中国的脏）上达到II类？'),

      H2('Гарантия / 保证'),
      ...item('9', 'Если выход или качество не выйдут на обещанное — что вы даёте: штраф, доделку, замену?',
        '若收率或质量未达承诺——您提供什么：罚款、整改、更换？'),

      spacer(),
      new Paragraph({
        spacing: { before: 120 },
        children: [new TextRun({ text: 'По каждой цифре просьба указывать: факт по вашему заводу / гарантия / оценка. / 请对每个数值注明：贵厂实测 / 保证值 / 估算。', italics: true, size: 18, color: '595959' })],
      }),
    ],
  }],
});

Packer.toBuffer(doc).then((buf) => {
  fs.writeFileSync(process.argv[2] || 'out_voprosy.docx', buf);
  console.log('Wrote', process.argv[2] || 'out_voprosy.docx', buf.length, 'bytes');
});

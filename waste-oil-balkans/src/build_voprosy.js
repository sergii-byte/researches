const fs = require('fs');
const { Document, Packer, Paragraph, TextRun, BorderStyle } = require('docx');
const H = require('./helpers');
const { title, subtitle, spacer } = H;

// One question: bold number + heading, detail line, then an answer line.
function item(n, head, detail) {
  return [
    new Paragraph({
      spacing: { before: 170, after: 20, line: 268 },
      children: [
        new TextRun({ text: n + '. ', bold: true, size: 23, color: '1F3864' }),
        new TextRun({ text: head, bold: true, size: 22 }),
      ],
    }),
    new Paragraph({
      spacing: { after: 60, line: 264 },
      children: H.runs(detail),
    }),
    new Paragraph({
      spacing: { after: 80, line: 300 },
      border: { bottom: { style: BorderStyle.DOTTED, size: 4, color: 'BBBBBB', space: 3 } },
      children: [new TextRun({ text: 'Ответ:', size: 19, color: '999999' })],
    }),
  ];
}

